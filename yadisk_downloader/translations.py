def t(language: str, key: str) -> str:
    """Translate ``key`` for ``language``, falling back to English."""
    return TRANSLATIONS.get(language, TRANSLATIONS["en"]).get(
        key, TRANSLATIONS["en"].get(key, key)
    )


def detect_system_language() -> str:
    """Return the system language code, falling back to ``"en"``."""
    try:
        code = (locale.getdefaultlocale()[0] or "").split("_")[0].lower()
    except Exception:
        return "en"
    return code if code in LANG_DISPLAY_NAMES else "en"
